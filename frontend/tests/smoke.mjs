import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const folder=mkdtempSync(join(tmpdir(),'cutline-browser-'));
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({baseURL:process.env.APP_URL||'http://127.0.0.1:5173',viewport:{width:1440,height:1000},httpCredentials:process.env.CUTLINE_TEST_PASSWORD?{username:process.env.CUTLINE_TEST_USERNAME||'test-owner',password:process.env.CUTLINE_TEST_PASSWORD}:undefined});
page.setDefaultTimeout(10000);
const errors=[];
const created=[];
page.on('pageerror',error=>errors.push(error.message));
try {
  await page.goto(process.env.APP_URL||'http://127.0.0.1:5173');
  await page.getByRole('heading',{name:'Long video. Endless potential.'}).waitFor();
  const health=await (await page.request.get('/api/health')).json();
  if(health.temporary_storage){
    await page.getByRole('note').filter({hasText:'Download your clips'}).waitFor();
    await page.getByRole('button',{name:'Workspace details'}).click();
    await page.getByText('Temporary on this server',{exact:true}).waitFor();
    await page.keyboard.press('Escape');
  }
  assert.equal(await page.locator('.storage-notice').count(),health.temporary_storage?1:0);
  if(health.free_demo){
    assert.equal(await page.locator('.language-setting select').inputValue(),'en');
    assert.equal(await page.locator('.language-setting select').isDisabled(),true);
    await page.getByText('Free demo · English recognition',{exact:true}).waitFor();
  }
  assert.equal(await page.getByRole('combobox',{name:'Framing',exact:true}).inputValue(),'auto');
  await page.getByRole('combobox',{name:'Framing',exact:true}).selectOption('stack');
  await page.getByRole('combobox',{name:'Source screen layout',exact:true}).selectOption('top_bottom');
  await page.getByRole('slider',{name:'Screen divider position'}).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('slider',{name:'Screen divider position'}).inputValue(),'51');
  await page.getByRole('combobox',{name:'Source screen layout',exact:true}).selectOption('side_by_side');
  await page.getByRole('combobox',{name:'Framing',exact:true}).selectOption('speaker');
  await page.getByRole('switch',{name:'Follow the speaker'}).waitFor();
  await page.getByText('Instant speaker changes · No transition',{exact:true}).waitFor();
  await page.getByRole('combobox',{name:'Framing',exact:true}).selectOption('scene');
  await page.getByRole('button',{name:'Create my clips'}).click();
  await page.getByRole('alert').filter({hasText:'Choose a video'}).waitFor();
  await page.getByRole('tab',{name:'YouTube link'}).click();
  await page.getByRole('textbox',{name:'YouTube video link'}).fill('https://example.com/video');
  await page.getByRole('button',{name:'Create my clips'}).click();
  await page.getByRole('alert').filter({hasText:'valid YouTube video link'}).waitFor();
  await page.locator('.nav-item').filter({hasText:'Caption styles'}).click();
  await page.locator('.template-card').filter({hasText:'Pop'}).click();
  await page.getByRole('status').filter({hasText:'Pop is your default'}).waitFor();
  await page.locator('.nav-item').filter({hasText:'Create clips'}).click();
  assert(await page.getByRole('button',{name:'Pop caption style'}).evaluate(e=>e.classList.contains('selected')));
  await page.getByRole('switch',{name:'Auto captions',exact:true}).click();
  assert.equal(await page.locator('.caption-style-select').count(),0);
  await page.getByRole('button',{name:'How Cutline works'}).click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.getByRole('tab',{name:'Upload a video'}).click();
  const video=join(folder,'short.mp4');
  execFileSync('ffmpeg',['-v','error','-y','-f','lavfi','-i','color=blue:s=160x90:r=5','-f','lavfi','-i','sine=frequency=440:sample_rate=16000','-t','1','-c:v','libx264','-c:a','aac',video]);
  await page.locator('input[type=file]').setInputFiles(video);
  await page.getByRole('alert').filter({hasText:'longer than 3 minutes'}).waitFor();
  await page.getByRole('group',{name:'Clipping mode'}).getByRole('button',{name:/Clip a time range/}).click();
  await page.getByRole('heading',{name:'Your video. Your exact moment.'}).waitFor();
  assert.equal(await page.getByRole('textbox',{name:'End time',exact:true}).inputValue(),'0:01');
  await page.getByRole('textbox',{name:'Start time',exact:true}).fill('0:00.75');
  await page.getByRole('textbox',{name:'End time',exact:true}).fill('0:00.25');
  await page.getByRole('button',{name:'Cut this range',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'valid start and end times'}).waitFor();
  await page.getByRole('textbox',{name:'End time',exact:true}).fill('0:02');
  await page.getByRole('button',{name:'Cut this range',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'beyond your'}).waitFor();
  await page.getByRole('textbox',{name:'Start time',exact:true}).fill('0:00.25');
  await page.getByRole('textbox',{name:'End time',exact:true}).fill('0:00.75');
  await page.getByRole('button',{name:'Preview selected range',exact:true}).click();
  await page.waitForFunction(()=>{const v=document.querySelector('.range-source-preview video');return v?.paused&&v.currentTime>=.7&&v.currentTime<.85;});
  for (const width of [320,390,768,1440]) {
    await page.setViewportSize({width,height:900});
    await page.waitForTimeout(300);
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}px`);
    await page.getByRole('combobox',{name:'Framing',exact:true}).selectOption('stack');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Stack controls overflow at ${width}px`);
    await page.getByRole('combobox',{name:'Framing',exact:true}).selectOption('scene');
  }
  await page.getByRole('tab',{name:'YouTube link'}).click();
  await page.getByRole('textbox',{name:'YouTube video link'}).fill('https://youtu.be/abcdefghijk');
  await page.getByText('Enter the times from the YouTube player.',{exact:false}).waitFor();
  assert.equal(await page.getByRole('textbox',{name:'Start time',exact:true}).inputValue(),'0:00.25');
  await page.getByRole('tab',{name:'Upload a video'}).click();
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/jobs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Cut this range',exact:true}).click();
  const response=await responsePromise;
  assert.equal(response.status(),202);
  const job=await response.json();
  created.push(job.id);
  const project=page.locator(`article[data-project-id="${job.id}"]`);
  await project.getByText('Ready to share',{exact:true}).waitFor({timeout:30000});
  const finished=await (await page.request.get(`/api/jobs/${job.id}`)).json();
  assert.equal(finished.clips.length,1);
  assert.equal(finished.clips[0].duration,.5);
  assert.equal(finished.clips[0].kind,'range');
  await project.getByRole('button',{name:'Make it yours'}).click();
  assert.equal(await page.getByRole('combobox',{name:'Download quality',exact:true}).inputValue(),'720p');
  await page.getByRole('combobox',{name:'Download quality',exact:true}).selectOption('480p');
  await page.getByRole('button',{name:'Frame',exact:true}).click();
  await page.getByRole('combobox',{name:'Framing',exact:true}).selectOption('stack');
  await page.getByRole('combobox',{name:'Source screen layout',exact:true}).selectOption('side_by_side');
  await page.getByRole('button',{name:'Export clip',exact:true}).click();
  await page.getByRole('link',{name:/Your MP4 is ready/}).waitFor({timeout:30000});
  const stacked=await (await page.request.get(`/api/jobs/${job.id}`)).json();
  assert.equal(stacked.clips[0].export_framing,'stack');
  assert.equal(stacked.clips[0].export_settings.quality,'480p');
  await page.getByText('MP4 · 480 × 854 · Yours to share',{exact:true}).waitFor();
  await page.getByRole('combobox',{name:'Framing',exact:true}).selectOption('speaker');
  await page.getByRole('switch',{name:'Follow the speaker'}).waitFor();
  await page.getByRole('button',{name:'Export clip',exact:true}).click();
  await page.getByRole('link',{name:/Your MP4 is ready/}).waitFor({timeout:30000});
  await page.keyboard.press('Escape');
  const speaker=(await (await page.request.get(`/api/jobs/${job.id}`)).json()).clips[0];
  await project.getByRole('button',{name:`Download ${speaker.title}`,exact:true}).click();
  await page.getByRole('heading',{name:'Download your clip',exact:true}).waitFor();
  assert.equal(await page.getByRole('combobox',{name:'Download quality',exact:true}).inputValue(),'480p');
  await page.getByRole('link',{name:'Download 480p MP4',exact:true}).waitFor();
  await page.getByRole('combobox',{name:'Download quality',exact:true}).selectOption('1080p');
  assert.equal(await page.getByRole('link',{name:'Download 480p MP4',exact:true}).count(),0);
  await page.getByText('MP4 · 1080 × 1920 · Yours to share',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Prepare download',exact:true}).click();
  assert.equal(await page.getByRole('combobox',{name:'Download quality',exact:true}).isDisabled(),true);
  await page.getByRole('link',{name:'Download 1080p MP4',exact:true}).waitFor({timeout:30000});
  const highQuality=(await (await page.request.get(`/api/jobs/${job.id}`)).json()).clips[0];
  assert.equal(highQuality.export_settings.quality,'1080p');
  assert.equal(highQuality.export_framing,'speaker');
  assert.notEqual(highQuality.export_url,speaker.export_url);
  const pendingDownload=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download 1080p MP4',exact:true}).click();
  const download=await pendingDownload;
  const downloaded=join(folder,'download-1080p.mp4');
  await download.saveAs(downloaded);
  const downloadedInfo=JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-of','json',downloaded],{encoding:'utf8'}));
  const downloadedVideo=downloadedInfo.streams.find(stream=>stream.codec_type==='video');
  assert.deepEqual([downloadedVideo.width,downloadedVideo.height],[1080,1920]);
  assert(downloadedInfo.streams.some(stream=>stream.codec_type==='audio'));
  for(const width of [320,390,768,1440]){
    await page.setViewportSize({width,height:900});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Quality dialog overflow at ${width}px`);
  }
  await page.keyboard.press('Escape');
  await project.getByRole('button',{name:'Make it yours'}).click();
  assert.equal(await page.getByRole('combobox',{name:'Download quality',exact:true}).inputValue(),'1080p');
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.locator('.nav-item').filter({hasText:'My projects'}).click();
  await page.getByRole('heading',{name:'Good stories live here.'}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('Browser smoke passed: validation, captions, framing, 480p editor export, saved quality, 1080p browser download with verified dimensions/audio, exact ranges, mobile navigation, and four responsive widths.');
} finally {
  for(const id of created){for(let attempt=0;attempt<120;attempt++){const result=await page.request.delete(`/api/jobs/${id}`).catch(()=>null);if(!result||result.status()!==409)break;await new Promise(resolve=>setTimeout(resolve,250));}}
  await browser.close();
  rmSync(folder,{recursive:true,force:true});
}
